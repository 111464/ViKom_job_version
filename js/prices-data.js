function priceEsc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function renderPriceTable(t, id) {
  const head = t.head.map((h) => `<th>${priceEsc(h)}</th>`).join("");
  const body = t.rows.map((r) =>
    `<tr>${r.map((c, i) => `<td${i === r.length - 1 || (i > 0 && c.length < 16) ? ' class="price-cell"' : ""}>${priceEsc(c)}</td>`).join("")}</tr>`
  ).join("");
  const unit = t.unit ? `<p class="price-note">${priceEsc(t.unit)}</p>` : "";
  const note = t.note ? `<p class="price-note">${priceEsc(t.note)}</p>` : "";
  return `<div class="price-block"${id ? ` id="t-${id}"` : ""}>
    <h3>${priceEsc(t.title)}</h3>${unit}
    <div class="price-table-wrap"><table class="price-table"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table></div>${note}
  </div>`;
}

/* Цены одной услуги; если таблиц нет — понятная заглушка со ссылкой на заявку */
function renderServicePrices(serviceId) {
  const svc = SERVICE_PRICES[serviceId];
  if (!svc) return "";
  if (!svc.tables.length) {
    return `<p class="price-empty">Стоимость этой услуги рассчитывается индивидуально. <a href="#contact-form">Оставьте заявку</a> — менеджер назовёт цену.</p>`;
  }
  return svc.tables.map((id) => renderPriceTable(PRICE_TABLES[id], id)).join("");
}


